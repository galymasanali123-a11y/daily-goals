# Fail fast if a key is missing on one side.
_en, _ru = STRINGS["en"], STRINGS["ru"]
_missing_ru = sorted(set(_en) - set(_ru))
_missing_en = sorted(set(_ru) - set(_en))
if _missing_ru or _missing_en:
    raise RuntimeError(f"i18n key mismatch ru={_missing_ru} en={_missing_en}")


def normalize_lang(value):
    text = (value or "").strip().lower()
    if text.startswith("ru"):
        return "ru"
    if text.startswith("en"):
        return "en"
    return None


def detect_lang(cookie=None, stored=None, accept=None):
    for candidate in (cookie, stored, accept):
        lang = normalize_lang(candidate)
        if lang:
            return lang
    return "en"


def current_lang():
    try:
        return getattr(g, "lang", None) or "en"
    except RuntimeError:
        return "en"


def t(key, **kwargs):
    lang = current_lang()
    catalog = STRINGS.get(lang) or STRINGS["en"]
    template = catalog.get(key) or STRINGS["en"].get(key) or key
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, ValueError):
            return template
    return template


def catalog_for(lang):
    lang = normalize_lang(lang) or "en"
    return STRINGS[lang]


def parse_accept_language(header):
    if not header:
        return None
    first = header.split(",")[0].strip()
    return first.split(";")[0].strip()
